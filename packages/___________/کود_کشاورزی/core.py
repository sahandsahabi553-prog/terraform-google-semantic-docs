def محاسبه_مقدار_کود_مورد_نیاز(
    مساحت_هکتار: float, میزان_مصرف_کیلوگرم_در_هکتار: float
) -> float:
    """
    مقدار کل کود مورد نیاز برای یک منطقه را محاسبه می‌کند.

    این تابع مقدار کل کود (بر حسب کیلوگرم) را بر اساس مساحت زمین (هکتار)
    و میزان مصرف توصیه شده (کیلوگرم در هکتار) محاسبه می‌کند.

    پارامترها:
        مساحت_هکتار (float): مساحت زمین بر حسب هکتار.
        میزان_مصرف_کیلوگرم_در_هکتار (float): میزان مصرف کود بر حسب کیلوگرم در هر هکتار.

    بازگشت:
        float: مقدار کل کود مورد نیاز بر حسب کیلوگرم.

    خطاها:
        ValueError: اگر `مساحت_هکتار` یا `میزان_مصرف_کیلوگرم_در_هکتار` غیرمثبت باشد.

    مثال:
        >>> محاسبه_مقدار_کود_مورد_نیاز(10.5, 200)
        2100.0
    """
    if مساحت_هکتار <= 0 or میزان_مصرف_کیلوگرم_در_هکتار <= 0:
        raise ValueError(
            "مساحت و میزان مصرف کود باید مقادیر مثبت باشند."
        )
    مقدار_کل_کود = مساحت_هکتار * میزان_مصرف_کیلوگرم_در_هکتار
    return مقدار_کل_کود


def محاسبه_غلظت_محلول(
    مقدار_کود_کیلوگرم: float, حجم_آب_لیتر: float
) -> float:
    """
    غلظت محلول کود را بر حسب گرم در لیتر (g/L) محاسبه می‌کند.

    این تابع غلظت محلول حاصل از حل کردن مقدار مشخصی کود (کیلوگرم)
    در حجم معینی از آب (لیتر) را محاسبه می‌کند.

    پارامترها:
        مقدار_کود_کیلوگرم (float): مقدار کود حل شده بر حسب کیلوگرم.
        حجم_آب_لیتر (float): حجم آب بر حسب لیتر.

    بازگشت:
        float: غلظت محلول بر حسب گرم در لیتر (g/L).

    خطاها:
        ValueError: اگر `مقدار_کود_کیلوگرم` یا `حجم_آب_لیتر` غیرمثبت باشد.

    مثال:
        >>> محاسبه_غلظت_محلول(2.5, 500) # 2.5 کیلوگرم در 500 لیتر آب
        5.0
    """
    if مقدار_کود_کیلوگرم <= 0 or حجم_آب_لیتر <= 0:
        raise ValueError(
            "مقدار کود و حجم آب باید مقادیر مثبت باشند."
        )
    # تبدیل کیلوگرم به گرم
    مقدار_کود_گرم = مقدار_کود_کیلوگرم * 1000
    غلظت = مقدار_کود_گرم / حجم_آب_لیتر
    return غلظت


